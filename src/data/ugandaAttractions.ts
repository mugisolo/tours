/**
 * Haversine great-circle distance in kilometers, multiplied by 1.28 road-winding factor
 * to provide realistic Ugandan road distance estimates.
 */
export function calculateRoadDistanceKm(
  lat1: number,
  lng1: number,
  lat2: number,
  lng2: number
): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const straightLine = R * c;
  return Math.round(straightLine * 1.28);
}

/**
 * Nearest-neighbor route optimizer starting from the first stop (or Kampala/Entebbe if present).
 */
export function optimizeItineraryStops(stops: Attraction[]): {
  ordered: Attraction[];
  legDistancesKm: number[];
  totalDistanceKm: number;
} {
  if (stops.length <= 1) {
    return { ordered: [...stops], legDistancesKm: [], totalDistanceKm: 0 };
  }

  const remaining = [...stops];
  // Prefer starting at Entebbe or Kampala if included, otherwise keep user's first selected stop
  const gatewayIdx = remaining.findIndex(
    (s) => s.id === 'entebbe-gateway' || s.id === 'kampala-city'
  );
  const startStop =
    gatewayIdx >= 0 ? remaining.splice(gatewayIdx, 1)[0] : remaining.shift()!;

  const ordered: Attraction[] = [startStop];
  const legDistancesKm: number[] = [];
  let totalDistanceKm = 0;

  while (remaining.length > 0) {
    const current = ordered[ordered.length - 1];
    let nearestIdx = 0;
    let minDistance = Infinity;

    for (let i = 0; i < remaining.length; i++) {
      const dist = calculateRoadDistanceKm(
        current.lat,
        current.lng,
        remaining[i].lat,
        remaining[i].lng
      );
      if (dist < minDistance) {
        minDistance = dist;
        nearestIdx = i;
      }
    }

    const nextStop = remaining.splice(nearestIdx, 1)[0];
    ordered.push(nextStop);
    legDistancesKm.push(minDistance);
    totalDistanceKm += minDistance;
  }

  return { ordered, legDistancesKm, totalDistanceKm };
}
